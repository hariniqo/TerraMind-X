import React, { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'
import { getAlerts } from '../services/api'
import { 
  Bell, 
  CheckSquare, 
  AlertTriangle, 
  CloudRain, 
  Droplets, 
  Activity, 
  TrendingUp, 
  FlaskConical, 
  ChevronRight,
  ShieldAlert,
  ArrowRight
} from 'lucide-react'

export function AlertsPage() {
  const [alerts, setAlerts] = useState<any[]>([])
  const [activeCategory, setActiveCategory] = useState<string>('ALL')

  useEffect(() => {
    getAlerts().then(setAlerts)
  }, [])

  const handleMarkAsRead = (id: string) => {
    setAlerts((prev) =>
      prev.map((alert) => (alert.id === id ? { ...alert, read: true } : alert))
    )
  }

  const handleMarkAllRead = () => {
    setAlerts((prev) => prev.map((alert) => ({ ...alert, read: true })))
  }

  const categories = ['ALL', 'WEATHER', 'IRRIGATION', 'CROP', 'DISEASE', 'MARKET', 'SOIL']

  const filteredAlerts = alerts.filter(a => {
    if (activeCategory === 'ALL') return true
    return a.category?.toUpperCase() === activeCategory
  })

  return (
    <div className="space-y-6 max-w-7xl mx-auto">
      
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-white dark:bg-[#0B2118] border border-terra-200 dark:border-white/10 p-6 rounded-[32px] shadow-sm">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <span className="px-2.5 py-0.5 rounded-full text-[10px] font-mono font-bold bg-amber-500/10 text-amber-600 dark:text-amber-400 border border-amber-500/20">
              🚨 MULTI-DOMAIN ANOMALY DETECTOR
            </span>
            <span className="text-xs text-terra-500 dark:text-white/40">Real-time alerts active</span>
          </div>
          <h1 className="text-2xl sm:text-3xl font-extrabold text-terra-950 dark:text-white tracking-tight">
            Agricultural Alert Center
          </h1>
          <p className="text-xs sm:text-sm text-terra-600 dark:text-white/70 mt-1">
            Proactive warnings generated by Soil Guardian, Climate Model, and AGMARKNET Market Engines.
          </p>
        </div>

        <button
          onClick={handleMarkAllRead}
          className="flex items-center gap-1.5 px-4 py-2.5 rounded-2xl bg-terra-50 hover:bg-terra-100 dark:bg-white/5 dark:hover:bg-white/10 text-xs font-bold text-terra-700 dark:text-white border border-terra-200 dark:border-white/10 transition self-start sm:self-center"
        >
          <CheckSquare className="h-4 w-4" />
          <span>Mark All as Read</span>
        </button>
      </div>

      {/* Category Filter Pills */}
      <div className="flex items-center gap-2 overflow-x-auto pb-1">
        {categories.map(cat => (
          <button
            key={cat}
            onClick={() => setActiveCategory(cat)}
            className={`px-3.5 py-2 rounded-2xl text-xs font-bold transition shrink-0 ${
              activeCategory === cat
                ? 'bg-emerald-600 text-white shadow-sm'
                : 'bg-white dark:bg-[#0B2118] border border-terra-200 dark:border-white/10 text-terra-700 dark:text-white/70 hover:bg-terra-50 dark:hover:bg-white/5'
            }`}
          >
            {cat}
          </button>
        ))}
      </div>

      {/* Alerts Grid Split by Severity */}
      <div className="grid gap-6 lg:grid-cols-3">
        
        {/* HIGH Priority */}
        <div className="space-y-4">
          <div className="flex items-center justify-between px-2">
            <h3 className="text-xs font-extrabold text-rose-600 dark:text-rose-400 uppercase tracking-widest flex items-center gap-2">
              <span className="w-2 h-2 rounded-full bg-rose-500 animate-ping" />
              High Priority Notices
            </h3>
            <span className="text-xs font-mono font-bold text-terra-400">
              {filteredAlerts.filter(a => a.severity === 'HIGH').length}
            </span>
          </div>

          <div className="space-y-3">
            {filteredAlerts.filter(a => a.severity === 'HIGH').map((alert) => (
              <div 
                key={alert.id} 
                className={`p-5 rounded-3xl border transition shadow-sm space-y-3 ${
                  alert.read 
                    ? 'bg-white/60 border-terra-200 dark:bg-white/5 dark:border-white/5 text-terra-500' 
                    : 'bg-white border-rose-200 dark:bg-[#1A0F0F] dark:border-rose-900/40'
                }`}
              >
                <div className="flex justify-between items-start gap-2">
                  <span className="px-2 py-0.5 rounded-md text-[10px] font-mono font-bold bg-rose-500/10 text-rose-600 dark:text-rose-400 uppercase">
                    {alert.category}
                  </span>
                  <span className="text-[10px] font-mono text-terra-400 dark:text-white/40">{alert.time}</span>
                </div>
                <h4 className="text-sm font-bold text-terra-950 dark:text-white">{alert.title}</h4>
                <p className="text-xs text-terra-700 dark:text-white/70 leading-relaxed">{alert.message}</p>
                
                <div className="pt-3 border-t border-terra-100 dark:border-white/5 flex items-center justify-between">
                  <Link
                    to="/ai-advisor?q=Help+me+resolve+this+alert"
                    className="text-xs font-bold text-emerald-600 dark:text-emerald-400 hover:underline flex items-center gap-1"
                  >
                    <span>Mitigate with AI</span>
                    <ArrowRight className="w-3.5 h-3.5" />
                  </Link>
                  {!alert.read && (
                    <button 
                      onClick={() => handleMarkAsRead(alert.id)}
                      className="text-xs font-bold text-terra-500 hover:text-terra-800 dark:text-white/60 dark:hover:text-white"
                    >
                      Dismiss
                    </button>
                  )}
                </div>
              </div>
            ))}
            {filteredAlerts.filter(a => a.severity === 'HIGH').length === 0 && (
              <div className="p-8 text-center bg-white dark:bg-[#0B2118] border border-terra-200 dark:border-white/10 rounded-3xl text-xs text-terra-500 dark:text-white/40">
                No active high-priority warnings in this category.
              </div>
            )}
          </div>
        </div>

        {/* MEDIUM Priority */}
        <div className="space-y-4">
          <div className="flex items-center justify-between px-2">
            <h3 className="text-xs font-extrabold text-amber-600 dark:text-amber-400 uppercase tracking-widest flex items-center gap-2">
              <span className="w-2 h-2 rounded-full bg-amber-500" />
              Medium Priority Advisories
            </h3>
            <span className="text-xs font-mono font-bold text-terra-400">
              {filteredAlerts.filter(a => a.severity === 'MEDIUM').length}
            </span>
          </div>

          <div className="space-y-3">
            {filteredAlerts.filter(a => a.severity === 'MEDIUM').map((alert) => (
              <div 
                key={alert.id} 
                className={`p-5 rounded-3xl border transition shadow-sm space-y-3 ${
                  alert.read 
                    ? 'bg-white/60 border-terra-200 dark:bg-white/5 dark:border-white/5 text-terra-500' 
                    : 'bg-white border-amber-200 dark:bg-[#1A170F] dark:border-amber-900/40'
                }`}
              >
                <div className="flex justify-between items-start gap-2">
                  <span className="px-2 py-0.5 rounded-md text-[10px] font-mono font-bold bg-amber-500/10 text-amber-600 dark:text-amber-400 uppercase">
                    {alert.category}
                  </span>
                  <span className="text-[10px] font-mono text-terra-400 dark:text-white/40">{alert.time}</span>
                </div>
                <h4 className="text-sm font-bold text-terra-950 dark:text-white">{alert.title}</h4>
                <p className="text-xs text-terra-700 dark:text-white/70 leading-relaxed">{alert.message}</p>
                
                <div className="pt-3 border-t border-terra-100 dark:border-white/5 flex items-center justify-between">
                  <Link
                    to="/ai-advisor"
                    className="text-xs font-bold text-emerald-600 dark:text-emerald-400 hover:underline flex items-center gap-1"
                  >
                    <span>View Protocol</span>
                    <ArrowRight className="w-3.5 h-3.5" />
                  </Link>
                  {!alert.read && (
                    <button 
                      onClick={() => handleMarkAsRead(alert.id)}
                      className="text-xs font-bold text-terra-500 hover:text-terra-800 dark:text-white/60 dark:hover:text-white"
                    >
                      Dismiss
                    </button>
                  )}
                </div>
              </div>
            ))}
            {filteredAlerts.filter(a => a.severity === 'MEDIUM').length === 0 && (
              <div className="p-8 text-center bg-white dark:bg-[#0B2118] border border-terra-200 dark:border-white/10 rounded-3xl text-xs text-terra-500 dark:text-white/40">
                No active medium-priority advisories.
              </div>
            )}
          </div>
        </div>

        {/* INFORMATIONAL & Low Priority */}
        <div className="space-y-4">
          <div className="flex items-center justify-between px-2">
            <h3 className="text-xs font-extrabold text-teal-600 dark:text-teal-400 uppercase tracking-widest flex items-center gap-2">
              <span className="w-2 h-2 rounded-full bg-teal-500" />
              Informational Updates
            </h3>
            <span className="text-xs font-mono font-bold text-terra-400">
              {filteredAlerts.filter(a => a.severity !== 'HIGH' && a.severity !== 'MEDIUM').length}
            </span>
          </div>

          <div className="space-y-3">
            {filteredAlerts.filter(a => a.severity !== 'HIGH' && a.severity !== 'MEDIUM').map((alert) => (
              <div 
                key={alert.id} 
                className="p-5 rounded-3xl bg-white dark:bg-[#0B2118] border border-terra-200 dark:border-white/10 shadow-sm space-y-3"
              >
                <div className="flex justify-between items-start gap-2">
                  <span className="px-2 py-0.5 rounded-md text-[10px] font-mono font-bold bg-teal-500/10 text-teal-600 dark:text-teal-400 uppercase">
                    {alert.category || 'INFO'}
                  </span>
                  <span className="text-[10px] font-mono text-terra-400 dark:text-white/40">{alert.time}</span>
                </div>
                <h4 className="text-sm font-bold text-terra-950 dark:text-white">{alert.title}</h4>
                <p className="text-xs text-terra-700 dark:text-white/70 leading-relaxed">{alert.message}</p>
                
                <div className="pt-3 border-t border-terra-100 dark:border-white/5 flex items-center justify-between">
                  <span className="text-[11px] text-emerald-600 dark:text-emerald-400 font-bold">Verified Feed</span>
                  {!alert.read && (
                    <button 
                      onClick={() => handleMarkAsRead(alert.id)}
                      className="text-xs font-bold text-terra-500 hover:text-terra-800 dark:text-white/60 dark:hover:text-white"
                    >
                      Dismiss
                    </button>
                  )}
                </div>
              </div>
            ))}
          </div>
        </div>

      </div>
    </div>
  )
}
